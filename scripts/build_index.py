"""Generate knowledge/INDEX.md — the chapter map of the knowledge base (D2).

Purpose: let any agent (with or without MCP) see every chapter of
kontext.md with its ID, exact line range and size *before* reading, so it
can read whole chapters selectively (e.g. `Read offset/limit`) or decide
to ingest complete files. Chapters are listed complete — an H2 chapter is
never split.

Chapter IDs and line ranges come from server/splitting.py, the same code
the MCP server uses (fetch, /mcp/kontext/<id>.md), so they cannot drift.

    uv run scripts/build_index.py           # (re)write knowledge/INDEX.md
    uv run scripts/build_index.py --check   # exit 1 if INDEX.md is stale

Re-run after every change to knowledge/kontext.md or bibliography.md.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "server"))

from splitting import (  # noqa: E402 — after sys.path setup
    KNOWLEDGE_DIR,
    _context_chapters,
    _scan_headers,
)

# Canonical public chapter URLs (FIDAA-DEMO deployment, server PUBLIC_URL default).
PUBLIC_URL = "https://fidaa.h2.de/mcp"
OUT = KNOWLEDGE_DIR / "INDEX.md"


def _tokens(chars: int) -> str:
    """Rough token estimate (≈3 chars/token for German — the server's
    MAX_CHUNK_CHARS rule; real tokenizers usually need somewhat fewer)."""
    return f"≈ {round(chars / 3, -2):,.0f}".replace(",", " ")


def _chars(n: int) -> str:
    return f"{n:,}".replace(",", " ")


def build() -> str:
    files = ["kontext.md", "bibliography.md", "systemprompt.md", "prompts.md", "welcome.md"]
    sizes = {f: len((KNOWLEDGE_DIR / f).read_text(encoding="utf-8")) for f in files}
    purpose = {
        "kontext.md": "Kontextdatenbank — das Fachwissen (Kapitel unten)",
        "bibliography.md": "Bibliografie — 140+ Quellen mit Kurzbeschreibung",
        "systemprompt.md": "Verhaltensregeln für einen KI-Agenten (FIDAA-Systemprompt)",
        "prompts.md": "9 Chat-Startervorlagen",
        "welcome.md": "Kurze Projektübersicht",
    }
    out = [
        "<!--",
        "SPDX-License-Identifier: CC-BY-SA-4.0",
        "Copyright (C) 2026 FIDAA contributors",
        "",
        "GENERATED by scripts/build_index.py — do not edit by hand.",
        "-->",
        "",
        "# FIDAA – Inhaltsverzeichnis der Wissensbasis",
        "",
        "Kapitelübersicht der Wissensdateien in `knowledge/`, für Agenten: erst "
        "hier die passenden Kapitel finden, dann **ganze Kapitel** lesen "
        "(Zeilenbereich in `kontext.md`, MCP-Tool `fetch(id)` oder die "
        "Kapitel-URL). Jedes `##`-Kapitel ist eine in sich vollständige, von "
        "Menschen redigierte Einheit — nie nur Teile davon verwenden.",
        "",
        "## Dateien",
        "",
        "| Datei | Inhalt | Zeichen | Tokens (grob) |",
        "| --- | --- | ---: | ---: |",
    ]
    for f in files:
        out.append(f"| `{f}` | {purpose[f]} | {_chars(sizes[f])} | {_tokens(sizes[f])} |")
    total = sum(sizes.values())
    out += [
        "",
        "## Ganzdatei-Ingestion",
        "",
        f"Alle Dateien zusammen: {_chars(total)} Zeichen ({_tokens(total)} Tokens, "
        "grobe Schätzung). Ein Agent mit ausreichend großem Kontextfenster kann "
        "`kontext.md` (und bei Bedarf `bibliography.md`) **vollständig** "
        "aufnehmen statt zu suchen — das vermeidet Lücken durch verpasste "
        "Suchtreffer. Wege: die Datei direkt lesen, "
        f"`{PUBLIC_URL}/knowledge/kontext.md` (HTTP), die MCP-Ressource "
        "`fidaa://knowledge/kontext.md` oder das MCP-Tool "
        "`read_knowledge_file` (in Teilen, nur an Kapitelgrenzen getrennt).",
        "",
        "## Kapitel der Kontextdatenbank (`kontext.md`)",
        "",
        f"Kapitel-URL: `{PUBLIC_URL}/kontext/<ID>.md` · MCP: `fetch(<ID>)`.",
        "",
    ]
    for n, ch in enumerate(_context_chapters(), start=1):
        ranges = ", ".join(f"{a}–{b}" for a, b in ch.line_ranges)
        # H3 subheadings = what the chapter covers (orientation only — the
        # chapter is still read whole).
        sub = [
            t
            for _, lv, t in _scan_headers(ch.text.split("\n"), (3,))
            if lv == 3 and t
        ]
        out.append(f"### {n}. {ch.heading_path[-1]}")
        out.append("")
        out.append(
            f"- ID `{ch.id}` · Zeilen {ranges} · {_chars(len(ch.text))} Zeichen "
            f"({_tokens(len(ch.text))} Tokens) · [Kapitel]({PUBLIC_URL}/kontext/{ch.id}.md)"
        )
        if sub:
            out.append("- Abschnitte: " + " · ".join(sub))
        out.append("")

    # Bibliography: thematic H1 sections with line ranges and entry counts.
    lines = (KNOWLEDGE_DIR / "bibliography.md").read_text(encoding="utf-8").split("\n")
    heads = _scan_headers(lines, (1,))
    out += ["## Bibliografie (`bibliography.md`)", "", "| Themenfeld | Zeilen | Einträge |", "| --- | --- | ---: |"]
    for k, (i, _, t) in enumerate(heads):
        end = heads[k + 1][0] if k + 1 < len(heads) else len(lines)
        entries = sum(1 for ln in lines[i:end] if ln.startswith("* **"))
        out.append(f"| {t} | {i + 1}–{end} | {entries} |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if INDEX.md is out of date")
    args = ap.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("knowledge/INDEX.md is out of date — run: uv run scripts/build_index.py")
            sys.exit(1)
        print("knowledge/INDEX.md is up to date.")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT} ({len(text)} chars, {len(_context_chapters())} chapters).")


if __name__ == "__main__":
    main()
